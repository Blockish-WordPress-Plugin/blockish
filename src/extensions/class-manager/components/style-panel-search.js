import { __ } from '@wordpress/i18n';

const normalizeSearch = (value) =>
    String(value || '')
        .toLowerCase()
        .replace(/[-_\s]+/g, '');

export const panelMatchesQuery = (query, terms) => {
    const needle = normalizeSearch(query);
    if (!needle) {
        return true;
    }

    return terms.some((term) => normalizeSearch(term).includes(needle));
};

